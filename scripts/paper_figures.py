"""Table and figure of the EGC 2027 article (French, RNTI single column).

Usage (after ``scripts/study_analysis.py bootstrap``, or directly from the
versioned ``results/aggregated/`` files)::

    python scripts/paper_figures.py

Writes ``results/paper/tab_auc.tex`` (Table 1: AUC of the main split, mean ±
standard deviation over seeds and paired-bootstrap 95 % interval) and
``results/paper/fig_pertes.pdf`` (Figure 1: AUC points lost at 12 dB of
mismatch and by the multi-condition model, with 95 % intervals). Text in French, decimal comma.
"""

from __future__ import annotations

import matplotlib
import pandas as pd

from noisemismatch.config import REPO_ROOT
from noisemismatch.eval.study import (
    CELL_KEYS,
    CONDITION_SNR,
    MODELS,
    RUN_KEYS,
    over_seeds,
)

matplotlib.use("pdf")
import matplotlib.pyplot as plt
from matplotlib.patches import Patch

AGG = REPO_ROOT / "results" / "aggregated"
OUT = REPO_ROOT / "results" / "paper"
NAMES: dict[str, str] = {
    "ae": "Auto-encodeur",
    "mobilenetv2": "MobileNetV2",
    "eat_knn": "EAT + kNN",
    "wilkinghoff": "Wilkinghoff",
    "osscl": "OS-SCL",
}


def fr(value: float, digits: int = 1) -> str:
    """French decimal comma; LaTeX minus sign."""
    text = f"{value:.{digits}f}".replace(".", "{,}")
    return text.replace("-", "$-$")


def intervals() -> pd.DataFrame:
    """Main-evaluation AUC intervals of the main split."""
    table = pd.read_csv(
        AGG / "bootstrap_intervals_main.csv", dtype={"test_snr_db": str, "model_b": str}
    )
    return table[(table["evaluation"] == "main") & (table["metric"] == "auc")]


def latex_table() -> str:
    """Table 1: AUC, main split."""
    agg = pd.read_csv(AGG / "aggregated.csv")
    agg = agg[agg["aggregation"] == "main"]
    seeds = over_seeds(
        agg[[*RUN_KEYS, "test_snr_db", "auc"]], "auc", CELL_KEYS
    ).set_index(CELL_KEYS)
    boot = intervals()
    boot = boot[boot["statistic"] == "level"].set_index(
        ["model", "train_condition", "test_snr_db"]
    )
    train = {"m6dB": "$-6$", "0dB": "0", "p6dB": "+6", "multi": "multi"}
    lines = [
        "% Generated by scripts/paper_figures.py from results/aggregated; do not edit.",
        "\\begin{table}[t]",
        " \\begin{center}",
        "  \\footnotesize",
        "  \\setlength{\\tabcolsep}{3.5pt}",
        "  \\begin{tabular}{llccc}",
        "  \\hline\\hline",
        "  Modèle & Entr. & Test $-6$\\,dB & Test 0\\,dB & Test +6\\,dB \\\\",
        "  \\hline",
    ]
    for i, model in enumerate(MODELS):
        if i:
            lines.append("  \\hline")
        for condition in CONDITION_SNR:
            cells = []
            for snr in (-6, 0, 6):
                s = seeds.loc[(model, condition, snr)]
                b = boot.loc[(model, condition, str(snr))]
                if (
                    abs(s["mean"] - b["estimate"]) > 2e-6
                ):  # both files have six decimals
                    raise ValueError(f"estimate differs: {model} {condition} {snr}")
                sd = "" if model == "eat_knn" else f"\\,$\\pm$\\,{fr(100 * s['std'])}"
                value = f"{fr(100 * s['mean'])}{sd}"
                if CONDITION_SNR[condition] == snr:
                    value = f"\\textbf{{{fr(100 * s['mean'])}}}{sd}"
                cells.append(
                    f"{value} [{fr(100 * b['low'])}\\,; {fr(100 * b['high'])}]"
                )
            lead = NAMES[model] if condition == "m6dB" else ""
            lines.append(
                f"  {lead} & {train[condition]} & " + " & ".join(cells) + " \\\\"
            )
    lines += [
        "  \\hline",
        "  \\end{tabular}",
        "  \\caption{AUC (\\%) des cinq modèles sur la partition principale de MIMII, "
        "selon le RSB d'entraînement (lignes, en dB) et le RSB de test (colonnes). "
        "Moyenne $\\pm$ écart-type sur trois graines et, entre crochets, intervalle "
        "de confiance à 95\\,\\% par bootstrap à tirages communs (échantillonnage des "
        "extraits de test). En gras : cellules appariées, où l'entraînement et le "
        "test ont le même RSB. Un $\\Delta$AUC est la différence avec la cellule en "
        "gras de la même colonne. EAT + kNN ne comporte aucun aléa (écart-type nul). "
        "Multi : modèle entraîné aux trois RSB, avec le même nombre de pas "
        "d'optimisation.}",
        "  \\label{tab:auc}",
        " \\end{center}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


LABEL_SIZE = 6.0  # points, values written after the bars


def losses() -> pd.DataFrame:
    """AUC points lost against the matched model, with the 95 % interval.

    One row per model and bar: (a) trained at +6 dB, tested at -6 dB; (b) trained
    at -6 dB, tested at +6 dB; (c) multi-condition model, worst of the three test
    SNRs (smallest ΔAUC). ``loss`` = -ΔAUC; a negative loss is a gain.
    """
    boot = intervals()
    boot = boot[boot["statistic"] == "delta"]
    rows = []
    for model in MODELS:
        part = boot[boot["model"] == model]
        cells = {
            "a": part[
                (part["train_condition"] == "p6dB") & (part["test_snr_db"] == "-6")
            ],
            "b": part[
                (part["train_condition"] == "m6dB") & (part["test_snr_db"] == "6")
            ],
            "c": part[part["train_condition"] == "multi"].nsmallest(1, "estimate"),
        }
        for bar, cell in cells.items():
            if len(cell) != 1:
                raise ValueError(f"{model} {bar}: {len(cell)} rows")
            r = cell.iloc[0]
            rows.append(
                {
                    "model": model,
                    "bar": bar,
                    "test_snr_db": r["test_snr_db"],
                    "loss": -100 * r["estimate"],
                    "low": -100 * r["high"],
                    "high": -100 * r["low"],
                }
            )
    return pd.DataFrame(rows)


def figure(path: str) -> None:
    """Grouped horizontal bars: AUC points lost, 95 % interval as error bars."""
    plt.rcParams.update(
        {
            "font.family": "STIXGeneral",
            "mathtext.fontset": "stix",
            "font.size": 8,
            "axes.linewidth": 0.6,
            "pdf.fonttype": 42,
            "axes.formatter.use_locale": False,
            "hatch.linewidth": 0.5,
        }
    )
    data = losses()
    styles = {  # readable in black and white: fill and hatching
        "a": {
            "color": "#3d3d3d",
            "hatch": None,
            "label": "entraîné à +6 dB, testé à −6 dB",
        },
        "b": {
            "color": "white",
            "hatch": "/////",
            "label": "entraîné à −6 dB, testé à +6 dB",
        },
        "c": {
            "color": "#bdbdbd",
            "hatch": None,
            "label": "multi-conditions, pire RSB de test",
        },
    }
    offsets = {"a": -0.335, "b": 0.0, "c": 0.335}
    fig, ax = plt.subplots(figsize=(13.2 / 2.54, 4.4 / 2.54))
    ax.axvline(0, color="black", linewidth=0.6, zorder=1)
    ax.grid(axis="x", color="#e4e3df", linewidth=0.5)
    ax.set_axisbelow(True)
    for _, r in data.iterrows():
        y = MODELS.index(r["model"]) + offsets[r["bar"]]
        style = styles[r["bar"]]
        ax.barh(
            y,
            max(r["loss"], 0.0),
            height=0.24,
            color=style["color"],
            hatch=style["hatch"],
            edgecolor="black",
            linewidth=0.5,
            zorder=2,
        )
        ax.errorbar(
            r["loss"],
            y,
            xerr=[[r["loss"] - r["low"]], [r["high"] - r["loss"]]],
            fmt="none",
            ecolor="black",
            elinewidth=0.6,
            capsize=1.2,
            capthick=0.6,
            zorder=3,
        )
        value = f"{abs(r['loss']):.1f}".replace(".", ",")
        text = value if r["loss"] >= 0 else f"gain {value}"
        # Centred on the bar by the height of the digits (0.66 em), not by the
        # text box, whose descent (the decimal comma) would pull it upwards.
        ax.annotate(
            text,
            xy=(max(r["high"], r["loss"], 0.0) + 0.25, y),
            xytext=(0, -0.33 * LABEL_SIZE),
            textcoords="offset points",
            va="baseline",
            fontsize=LABEL_SIZE,
        )
    ax.set_yticks(range(len(MODELS)))
    ax.set_yticklabels([NAMES[m] for m in MODELS])
    ax.set_ylim(len(MODELS) - 0.55, -0.55)
    ax.set_xlim(-1.5, 25.0)
    ax.set_xticks(range(0, 26, 5))
    ax.set_xlabel("Points d'AUC perdus face au modèle apparié")
    ax.tick_params(axis="y", length=0)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    handles = [
        Patch(
            facecolor=styles[k]["color"],
            hatch=styles[k]["hatch"],
            edgecolor="black",
            linewidth=0.5,
            label=styles[k]["label"],
        )
        for k in ("a", "b", "c")
    ]
    ax.legend(
        handles=handles,
        loc="center right",
        bbox_to_anchor=(1.0, 0.45),
        frameon=False,
        fontsize=6.5,
        handlelength=1.6,
        handleheight=0.9,
    )
    fig.tight_layout(pad=0.3)
    fig.savefig(
        path, metadata={"CreationDate": None, "Creator": None, "Producer": None}
    )
    plt.close(fig)


def main() -> int:
    """Writes the table and the figure.

    Returns:
        0 on success.
    """
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tab_auc.tex").write_text(latex_table(), encoding="utf-8")
    figure(str(OUT / "fig_pertes.pdf"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
